hub := Hub()
param s: Scalar over (-0.06, 1)
blade_a := solid({ p | some s: p in BladeSection(prop.stack_a, prop.fwd).profile at s })
blade_b := solid({ p | some s: p in BladeSection(prop.stack_b, prop.fwd).profile at s })

// the propeller as one part, for the foundry or the machine: the hub, its cap and both blades
use std.solids (union)
propeller := solid(hub.barrel)
hub.cap union propeller
blade_a union propeller
blade_b union propeller
