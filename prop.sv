// The propeller's datums: its centre on the tail's axis, the shaft's forward axis, and each blade's
// radial stacking line, hub to tip, square to the shaft in the centreplane (blade A up at rest).
component Propeller() {
  td := dims.tail_down
  c0 := point hint((6295, 0, -72))
  fix((dims.joint_x + dims.tail * cos(td), 0mm, dims.joint_z - dims.tail * sin(td))) c0
  ahead := point hint((6197, 0, -52))
  fix((dims.joint_x + (dims.tail - 100mm) * cos(td), 0mm, dims.joint_z - (dims.tail - 100mm) * sin(td))) ahead
  fwd_line := line(c0, ahead)
  fwd := axis
  fwd parallel(sense: same) fwd_line
  a_root := point hint((6300, 0, -44))
  fix((dims.joint_x + dims.tail * cos(td) + prop_hub * sin(td), 0mm, dims.joint_z - dims.tail * sin(td) + prop_hub * cos(td))) a_root
  a_tip := point hint((6321, 0, 60))
  fix((dims.joint_x + dims.tail * cos(td) + prop_R * sin(td), 0mm, dims.joint_z - dims.tail * sin(td) + prop_R * cos(td))) a_tip
  b_root := point hint((6290, 0, -99))
  fix((dims.joint_x + dims.tail * cos(td) - prop_hub * sin(td), 0mm, dims.joint_z - dims.tail * sin(td) - prop_hub * cos(td))) b_root
  b_tip := point hint((6269, 0, -204))
  fix((dims.joint_x + dims.tail * cos(td) - prop_R * sin(td), 0mm, dims.joint_z - dims.tail * sin(td) - prop_R * cos(td))) b_tip
  stack_a := line(a_root, a_tip)
  stack_b := line(b_root, b_tip)
}

// the hub: a cylinder on the shaft's axis, its radius the blades' root radius, 40 long, capped aft
component Hub() {
  td := dims.tail_down
  fwd := point hint((6286, 0, -67))
  fix((dims.joint_x + (dims.tail - 22mm) * cos(td), 0mm, dims.joint_z - (dims.tail - 22mm) * sin(td))) fwd
  aft := point hint((6326, 0, -75))
  fix((dims.joint_x + (dims.tail + 18mm) * cos(td), 0mm, dims.joint_z - (dims.tail + 18mm) * sin(td))) aft
  ax := line(fwd, aft)
  barrel := solid(std.sets.Rod(ax, r: prop_hub))
  cap := solid(std.sets.Ball(aft, r: prop_hub))
}

